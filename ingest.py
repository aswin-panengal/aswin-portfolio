"""Back up and synchronize the portfolio knowledge base without duplicate chunks."""

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sys
import uuid
from datetime import datetime, timezone

from dotenv import load_dotenv
from google import genai
from google.genai import types
from qdrant_client import QdrantClient
from qdrant_client.models import Distance, PointIdsList, PointStruct, VectorParams


ROOT = Path(__file__).resolve().parent
SOURCE = "aswin_knowledge_base.md"
MODEL = "gemini-embedding-001"
DIMENSIONS = 3072
SECTION = re.compile(r"^## SECTION (\d+):[^\n]+", re.MULTILINE)


def read_sections(path):
    content = path.read_text(encoding="utf-8")
    headings = list(SECTION.finditer(content))
    if not headings:
        raise ValueError(f"No knowledge-base sections found in {path.name}")
    sections = {}
    for index, heading in enumerate(headings):
        number = int(heading.group(1))
        if number in sections:
            raise ValueError(f"Duplicate section number: {number}")
        end = headings[index + 1].start() if index + 1 < len(headings) else len(content)
        sections[number] = content[heading.start():end].strip()
    return content, sections


def legacy_chunks(content):
    """Recognize only exact chunks generated by the previous ingestion script."""
    return {"SECTION " + part.strip() for part in content.split("SECTION") if len(part.strip()) > 50}


def point_id(number):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"aswin-portfolio/{SOURCE}/section/{number}"))


def ingest(previous_knowledge_base=None, dry_run=False):
    load_dotenv(ROOT / ".env.local")
    content, sections = read_sections(ROOT / SOURCE)
    previous_content = None
    if previous_knowledge_base:
        previous_content, previous_sections = read_sections(previous_knowledge_base)
        missing = set(previous_sections) - set(sections)
        if missing:
            raise ValueError(f"Refusing to drop existing sections: {sorted(missing)}")
    collection = os.getenv("QDRANT_COLLECTION_NAME", "aswin_portfolio_v4").strip()
    print(f"Knowledge base: {len(sections)} sections; collection: {collection}", flush=True)
    if dry_run:
        for number, text in sections.items():
            print(f"  {text.splitlines()[0]} ({len(text)} characters)")
        return

    for name in ("GEMINI_API_KEY", "QDRANT_URL", "QDRANT_API_KEY"):
        if not os.getenv(name):
            raise ValueError(f"Missing {name}; no database changes made")

    qdrant = QdrantClient(url=os.environ["QDRANT_URL"], api_key=os.environ["QDRANT_API_KEY"], timeout=30)
    exists = qdrant.collection_exists(collection)
    records = []
    config = None
    if exists:
        info = qdrant.get_collection(collection)
        config = info.config.params.vectors
        if not isinstance(config, VectorParams) or config.size != DIMENSIONS or config.distance != Distance.COSINE:
            raise ValueError("Collection vector configuration differs; refusing to modify it")
        offset = None
        while True:
            page, offset = qdrant.scroll(collection, limit=100, offset=offset, with_payload=True, with_vectors=True)
            records.extend(page)
            if offset is None:
                break

    # Headings alone never authorize replacing cloud-only content.
    recognized_legacy = legacy_chunks(content)
    if previous_content is not None:
        recognized_legacy |= legacy_chunks(previous_content)
    expected_ids = {point_id(number) for number in sections}
    legacy_ids = []
    for record in records:
        payload = record.payload or {}
        if payload.get("source") == SOURCE:
            if payload.get("section") not in sections:
                raise ValueError("Cloud contains a managed section missing locally; merge it before ingestion")
        elif payload.get("text") in recognized_legacy:
            legacy_ids.append(record.id)
        elif str(record.id) in expected_ids:
            raise ValueError("A planned point ID belongs to unknown data; refusing to overwrite it")

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup_root = Path(os.getenv("LOCALAPPDATA", str(Path.home()))) / "aswin-portfolio" / "backups"
    backup = backup_root / stamp
    backup.mkdir(parents=True)
    (backup / SOURCE).write_text(content, encoding="utf-8")
    snapshot = {
        "collection": collection,
        "vectors_config": config.model_dump(mode="json") if config else None,
        "points": [record.model_dump(mode="json") for record in records],
    }
    (backup / "qdrant-before.json").write_text(json.dumps(snapshot), encoding="utf-8")
    print(f"Backed up {len(records)} existing points to {backup}", flush=True)

    # Generate and validate every embedding before the first database write.
    print(f"Generating {len(sections)} embeddings with {MODEL}...", flush=True)
    with genai.Client(api_key=os.environ["GEMINI_API_KEY"]) as client:
        response = client.models.embed_content(
            model=MODEL,
            contents=list(sections.values()),
            config=types.EmbedContentConfig(output_dimensionality=DIMENSIONS),
        )
    embeddings = response.embeddings or []
    if len(embeddings) != len(sections):
        raise ValueError("Embedding count mismatch; no database changes made")
    points = []
    for (number, text), embedding in zip(sections.items(), embeddings):
        vector = embedding.values or []
        if len(vector) != DIMENSIONS or not all(math.isfinite(value) for value in vector):
            raise ValueError(f"Invalid vector for section {number}; no database changes made")
        points.append(PointStruct(id=point_id(number), vector=vector, payload={
            "text": text,
            "source": SOURCE,
            "section": number,
            "title": text.splitlines()[0],
            "content_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "embedding_model": MODEL,
        }))

    if not exists:
        qdrant.create_collection(collection, vectors_config=VectorParams(size=DIMENSIONS, distance=Distance.COSINE))
    qdrant.upsert(collection, points=points, wait=True)
    saved = qdrant.retrieve(collection, ids=[point.id for point in points], with_payload=True, with_vectors=True)
    expected = {str(point.id): point for point in points}
    if len(saved) != len(points) or any(
        record.payload != expected[str(record.id)].payload
        or not isinstance(record.vector, list) or len(record.vector) != DIMENSIONS
        for record in saved
    ):
        raise RuntimeError(f"Upload verification failed; old points retained. Backup: {backup}")

    # Only remove backed-up, exactly recognized legacy copies after replacement
    # points are confirmed. All other cloud data stays in place.
    legacy_ids = [value for value in legacy_ids if str(value) not in expected_ids]
    if legacy_ids:
        qdrant.delete(collection, points_selector=PointIdsList(points=legacy_ids), wait=True)
        if qdrant.retrieve(collection, ids=legacy_ids, with_payload=False, with_vectors=False):
            raise RuntimeError("Some legacy copies remain; inspect the collection before retrying")
    print(f"Verified {len(points)} current sections; replaced {len(legacy_ids)} legacy copies.", flush=True)
    print(f"Preserved {len(records) - len(legacy_ids) - sum(str(record.id) in expected_ids for record in records)} unrelated points.")
    print("Knowledge base is live.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Validate and list local sections without network access")
    parser.add_argument("--previous-knowledge-base", type=Path, help="Previous local source used to recognize and replace legacy chunks safely")
    args = parser.parse_args()
    try:
        ingest(args.previous_knowledge_base, args.dry_run)
    except Exception as error:
        print(f"Ingestion failed ({type(error).__name__}): {error}", file=sys.stderr)
        sys.exit(1)
